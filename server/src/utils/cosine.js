// Cosine similarity between two equal-length dense vectors (e.g. embedding outputs).
// Pure math, no dependencies — kept separate from utils/tfidf.js because that file's
// cosine works over sparse Map-based term vectors, not plain arrays.
export function cosineSimilarity(a, b) {
  let dot = 0, normA = 0, normB = 0;
  for (let i = 0; i < a.length; i++) {
    dot += a[i] * b[i];
    normA += a[i] * a[i];
    normB += b[i] * b[i];
  }
  if (normA === 0 || normB === 0) return 0;
  return dot / (Math.sqrt(normA) * Math.sqrt(normB));
}
